CREATE TABLE IF NOT EXISTS `ka_dogassignments` (
    `Id` int NOT NULL AUTO_INCREMENT,
    `DogId` int NOT NULL,
    `HandlerUserId` varchar(255) NULL,
    `BranchId` int NULL,
    `AssignedOn` datetime(6) NOT NULL,
    `EndedOn` datetime(6) NULL,
    `Notes` longtext NULL,
    `Uuid` longtext NULL,
    `CreatedAt` datetime(6) NOT NULL,
    `UpdatedAt` datetime(6) NULL,
    `DeletedAt` datetime(6) NULL,
    `CreatedBy` longtext NULL,
    `UpdatedBy` longtext NULL,
    `DeletedBy` longtext NULL,
    `IsDeleted` tinyint(1) NOT NULL DEFAULT 0,
    `IsActive` tinyint(1) NOT NULL DEFAULT 1,
    `CompanyId` int NOT NULL,
    PRIMARY KEY (`Id`),
    INDEX `IX_ka_dogassignments_DogId` (`DogId`),
    INDEX `IX_ka_dogassignments_HandlerUserId` (`HandlerUserId`),
    INDEX `IX_ka_dogassignments_BranchId` (`BranchId`),
    INDEX `IX_ka_dogassignments_CompanyId` (`CompanyId`),
    CONSTRAINT `FK_ka_dogassignments_ka_dogs_DogId` FOREIGN KEY (`DogId`) REFERENCES `ka_dogs` (`Id`) ON DELETE RESTRICT,
    CONSTRAINT `FK_ka_dogassignments_AspNetUsers_HandlerUserId` FOREIGN KEY (`HandlerUserId`) REFERENCES `AspNetUsers` (`Id`) ON DELETE RESTRICT,
    CONSTRAINT `FK_ka_dogassignments_ka_companies_BranchId` FOREIGN KEY (`BranchId`) REFERENCES `ka_companies` (`Id`) ON DELETE RESTRICT,
    CONSTRAINT `FK_ka_dogassignments_ka_companies_CompanyId` FOREIGN KEY (`CompanyId`) REFERENCES `ka_companies` (`Id`) ON DELETE CASCADE
) CHARACTER SET=utf8mb4;

CREATE TABLE IF NOT EXISTS `ka_dogcarerecords` (
    `Id` int NOT NULL AUTO_INCREMENT,
    `DogId` int NOT NULL,
    `EventType` varchar(50) NOT NULL,
    `OccurredOn` datetime(6) NOT NULL,
    `Details` longtext NULL,
    `QuantityOrOutcome` longtext NULL,
    `RequiresAttention` tinyint(1) NOT NULL DEFAULT 0,
    `RecordedByUserId` varchar(255) NULL,
    `Uuid` longtext NULL,
    `CreatedAt` datetime(6) NOT NULL,
    `UpdatedAt` datetime(6) NULL,
    `DeletedAt` datetime(6) NULL,
    `CreatedBy` longtext NULL,
    `UpdatedBy` longtext NULL,
    `DeletedBy` longtext NULL,
    `IsDeleted` tinyint(1) NOT NULL DEFAULT 0,
    `IsActive` tinyint(1) NOT NULL DEFAULT 1,
    `CompanyId` int NOT NULL,
    PRIMARY KEY (`Id`),
    INDEX `IX_ka_dogcarerecords_DogId_OccurredOn` (`DogId`, `OccurredOn`),
    INDEX `IX_ka_dogcarerecords_RecordedByUserId` (`RecordedByUserId`),
    INDEX `IX_ka_dogcarerecords_CompanyId` (`CompanyId`),
    CONSTRAINT `FK_ka_dogcarerecords_ka_dogs_DogId` FOREIGN KEY (`DogId`) REFERENCES `ka_dogs` (`Id`) ON DELETE RESTRICT,
    CONSTRAINT `FK_ka_dogcarerecords_AspNetUsers_RecordedByUserId` FOREIGN KEY (`RecordedByUserId`) REFERENCES `AspNetUsers` (`Id`) ON DELETE RESTRICT,
    CONSTRAINT `FK_ka_dogcarerecords_ka_companies_CompanyId` FOREIGN KEY (`CompanyId`) REFERENCES `ka_companies` (`Id`) ON DELETE CASCADE
) CHARACTER SET=utf8mb4;
